"""
Pipeline (end-to-end) evaluation: Correctness and Completeness.

Reuses the answers already generated by eval_generator.py (saved in
eval_generator_results.json) instead of re-running retrieval + generation —
we just need to judge those same answers against the golden reference_answer.

  - Correctness  — does the answer's content match the reference answer?
  - Completeness — does the answer cover everything the reference answer covers?

(Contextual Relevancy, the third pipeline metric from the original plan, was
already computed in eval_retrieval.py.)
"""

import json
from pathlib import Path

from deepeval.metrics import GEval
from deepeval.test_case import LLMTestCase, SingleTurnParams

from eval_retrieval import _measure_with_retry

GOLDEN_FILE = Path("golden_dataset.jsonl")
GENERATOR_RESULTS_FILE = Path("eval_generator_results.json")
RESULTS_FILE = Path("eval_pipeline_results.json")

CORRECTNESS_CRITERIA = (
    "Determine whether the actual output is factually correct and consistent "
    "with the expected output. Minor differences in wording, phrasing, or "
    "extra citation markers are fine as long as the facts, names, numbers, "
    "and conclusions match. If the actual output correctly states that the "
    "context did not contain enough information to answer, and the expected "
    "output shows an answer WAS available, that counts as incorrect."
)

COMPLETENESS_CRITERIA = (
    "Determine whether the actual output covers all the key information "
    "present in the expected output. The actual output does not need to "
    "match the wording, but it should not omit any material fact, item, or "
    "list entry that appears in the expected output."
)


def load_golden() -> dict[str, dict]:
    with GOLDEN_FILE.open(encoding="utf-8") as f:
        return {json.loads(line)["question_id"]: json.loads(line) for line in f}


def load_generated_answers() -> list[dict]:
    data = json.loads(GENERATOR_RESULTS_FILE.read_text(encoding="utf-8"))
    return data["per_question"]


def evaluate_pipeline(golden_by_id: dict[str, dict], generated: list[dict]) -> dict:
    correctness_metric = GEval(
        name="Correctness",
        criteria=CORRECTNESS_CRITERIA,
        evaluation_params=[
            SingleTurnParams.INPUT,
            SingleTurnParams.ACTUAL_OUTPUT,
            SingleTurnParams.EXPECTED_OUTPUT,
        ],
    )
    completeness_metric = GEval(
        name="Completeness",
        criteria=COMPLETENESS_CRITERIA,
        evaluation_params=[
            SingleTurnParams.INPUT,
            SingleTurnParams.ACTUAL_OUTPUT,
            SingleTurnParams.EXPECTED_OUTPUT,
        ],
    )

    correctness_scores, completeness_scores = [], []
    per_question = []

    for i, item in enumerate(generated, start=1):
        golden = golden_by_id[item["question_id"]]
        print(f"  [{i}/{len(generated)}] {item['question_id']}: {golden['question'][:60]}")

        tc = LLMTestCase(
            input=golden["question"],
            actual_output=item["answer"],
            expected_output=golden["reference_answer"],
        )
        c_score = _measure_with_retry(correctness_metric, tc, "Correctness", item["question_id"])
        m_score = _measure_with_retry(completeness_metric, tc, "Completeness", item["question_id"])
        if c_score is not None:
            correctness_scores.append(c_score)
        if m_score is not None:
            completeness_scores.append(m_score)

        per_question.append(
            {
                "question_id": item["question_id"],
                "question": golden["question"],
                "answer": item["answer"],
                "reference_answer": golden["reference_answer"],
                "correctness": c_score,
                "completeness": m_score,
            }
        )

    return {
        "correctness": sum(correctness_scores) / len(correctness_scores) if correctness_scores else None,
        "correctness_n": len(correctness_scores),
        "completeness": sum(completeness_scores) / len(completeness_scores) if completeness_scores else None,
        "completeness_n": len(completeness_scores),
        "per_question": per_question,
    }


def main():
    golden_by_id = load_golden()
    generated = load_generated_answers()
    print(f"Loaded {len(generated)} previously-generated answers")

    print("\n=== Pipeline evaluation (correctness + completeness vs. golden reference) ===")
    results = evaluate_pipeline(golden_by_id, generated)

    n = len(generated)

    def fmt(score, k):
        return f"{score:.3f} (n={k}/{n})" if score is not None else f"N/A (0/{n} succeeded)"

    print("\n" + "=" * 60)
    print("PIPELINE QUALITY")
    print(f"  Correctness:  {fmt(results['correctness'], results['correctness_n'])}")
    print(f"  Completeness: {fmt(results['completeness'], results['completeness_n'])}")

    with RESULTS_FILE.open("w", encoding="utf-8") as f:
        json.dump(results, f, indent=2, ensure_ascii=False)
    print(f"\nSaved full results to {RESULTS_FILE}")


if __name__ == "__main__":
    main()
